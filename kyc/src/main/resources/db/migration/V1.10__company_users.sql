CREATE TYPE ownership_status AS ENUM ('ACTIVE', 'INVITED', 'SUSPENDED');

ALTER TABLE ownership
    ADD COLUMN status          ownership_status NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN permission_mask integer          NOT NULL DEFAULT 0;

UPDATE ownership SET permission_mask = 255 WHERE type IN ('USER', 'AFFILIATE');
UPDATE ownership SET type = 'USER', permission_mask = 11 WHERE type = 'USER_DRAFT';
UPDATE ownership SET type = 'USER', permission_mask = 1 WHERE type = 'USER_READ';
UPDATE email_verification SET type = 'USER' WHERE type IN ('USER_DRAFT', 'USER_READ');

CREATE TEMPORARY TABLE duplicate_user_ownership AS
SELECT id, keeper_id
FROM (SELECT id,
             first_value(id) OVER (PARTITION BY account_id, company_id
                                   ORDER BY permission_mask DESC, last_used DESC NULLS LAST, id) AS keeper_id
      FROM ownership
      WHERE type = 'USER') ranked
WHERE id <> keeper_id;
UPDATE email_verification
SET requester_ownership_id = duplicate_user_ownership.keeper_id
FROM duplicate_user_ownership
WHERE email_verification.requester_ownership_id = duplicate_user_ownership.id;
DELETE FROM ownership
USING duplicate_user_ownership
WHERE ownership.id = duplicate_user_ownership.id;
DROP TABLE duplicate_user_ownership;

DELETE FROM ownership admin_row
USING account app_account
WHERE admin_row.account_id = app_account.id
  AND app_account.external_id = '${app-account-external-id}'::uuid
  AND admin_row.type = 'ADMIN'
  AND EXISTS (SELECT 1
              FROM ownership app_row
              WHERE app_row.account_id = admin_row.account_id
                AND app_row.company_id = admin_row.company_id
                AND app_row.type = 'APP');
UPDATE ownership
SET type = 'APP'
FROM account app_account
WHERE ownership.account_id = app_account.id
  AND app_account.external_id = '${app-account-external-id}'::uuid
  AND ownership.type = 'ADMIN';

CREATE TABLE ownership_invitation (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ownership_id          bigint NOT NULL UNIQUE,
    invited_by_account_id bigint,
    invited_name          varchar(255) NOT NULL,
    token                 varchar(64) NOT NULL UNIQUE,
    expires_on            timestamp with time zone NOT NULL,
    created_on            timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_ownership_invitation_ownership
        FOREIGN KEY (ownership_id) REFERENCES ownership(id) ON DELETE CASCADE,
    CONSTRAINT fk_ownership_invitation_invited_by
        FOREIGN KEY (invited_by_account_id) REFERENCES account(id) ON DELETE SET NULL
);

CREATE INDEX idx_ownership_company_status ON ownership(company_id, status);
CREATE UNIQUE INDEX uq_ownership_user_per_company ON ownership(account_id, company_id) WHERE type = 'USER';
